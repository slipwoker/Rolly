"""Collects every raw result file in benchmarks/results/ into reports/benchmark_summary.{json,md}.

    python -m benchmarks.analyze

The markdown is what BENCHMARKS.md quotes; nothing is typed by hand.
"""
from __future__ import annotations

import glob
import json
import re
from pathlib import Path

import jiwer

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "benchmarks" / "results"
OUT = ROOT / "reports"


def load(pattern: str) -> list[dict]:
    out = []
    for f in sorted(glob.glob(str(RES / pattern))):
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        d["_file"] = Path(f).name
        out.append(d)
    return out


def pct(x) -> str:
    return "–" if x is None else f"{x * 100:.1f}%"


def stat(s: dict | None, key: str = "median") -> str:
    return "–" if not s or not s.get("n") else f"{s[key]:.0f}"


def main() -> None:
    summary: dict = {}
    L: list[str] = ["# Benchmark summary (generated)", "",
                    "Generated by `python -m benchmarks.analyze` from the raw files in `benchmarks/results/`.", ""]

    # ---- STT WER ------------------------------------------------------------
    rows = []
    for d in load("stt_wer_*.json"):
        for r in d["results"]:
            utts = r["utterances"]
            pure = [u for u in utts if not re.search(r"[0-9a-z]", u["ref"])] if d["language"] == "he" else utts
            rows.append({"lang": d["language"], "model": r["model"], "snr_db": r["snr_db"], "n": len(utts), "wer": r["wer"], "cer": r["cer"],
                         "wer_no_digits_latin": round(jiwer.wer([u["ref"] for u in pure], [u["hyp"] for u in pure]), 4) if pure else None,
                         "n_no_digits_latin": len(pure), "rtf_cpu": r["rtf"], "file": d["_file"], "host": d["host"]})
    if rows:
        summary["stt_wer"] = rows
        L += ["## Speech recognition accuracy — FLEURS test, real human speech", "",
              "| Language | Model | Noise (SNR) | Utterances | WER | CER | WER, references without digits/Latin (n) |", "|---|---|---|---:|---:|---:|---:|"]
        order = {"clean": 99}
        for r in sorted(rows, key=lambda r: (r["lang"], r["model"], -order.get(r["snr_db"], float(r["snr_db"]) if r["snr_db"] != "clean" else 0))):
            snr = "clean" if r["snr_db"] == "clean" else f"{r['snr_db']} dB road noise"
            extra = f"{pct(r['wer_no_digits_latin'])} ({r['n_no_digits_latin']})" if r["lang"] == "he" else "–"
            L.append(f"| {r['lang']} | `{r['model']}` | {snr} | {r['n']} | {pct(r['wer'])} | {pct(r['cer'])} | {extra} |")
        L.append("")

    # ---- VAD ---------------------------------------------------------------
    vads = load("vad_endpointing_*.json")
    if vads:
        v = vads[-1]
        summary["vad"] = v
        L += ["## Endpointing and barge-in detection (Silero VAD, hardware independent)", "",
              f"Configuration: start after {v['config']['min_speech_ms']:.0f} ms of speech ({v['config']['bargein_min_speech_ms']:.0f} ms while the agent is audible), "
              f"eager point at {v['config']['eager_silence_ms']:.0f} ms of silence, endpoint at {v['config']['endpoint_silence_ms']:.0f} ms. "
              f"{v['n_utterances']} FLEURS utterances (Hebrew and English).", "",
              "| Noise (SNR) | Barge-in detection after true speech onset, median / p95 (ms) | Eager point after true end of speech, median (ms) | Endpoint after true end of speech, median / p95 (ms) | Missed utterances | Utterances split by a pause |",
              "|---|---:|---:|---:|---:|---:|"]
        for c in v["conditions"]:
            snr = "clean" if c["snr_db"] == "clean" else f"{c['snr_db']} dB"
            L.append(f"| {snr} | {stat(c['barge_in_onset_detect_ms'])} / {stat(c['barge_in_onset_detect_ms'], 'p95')} | {stat(c['eager_point_after_speech_end_ms'])} | "
                     f"{stat(c['endpoint_after_speech_end_ms'])} / {stat(c['endpoint_after_speech_end_ms'], 'p95')} | {c['missed_utterances']} of {2 * c['n_per_mode']} | {c['utterances_split_by_pause']} of {c['n_per_mode']} |")
        L += ["", "False barge-ins on road noise alone (2 minutes, agent audible): " +
              ", ".join(f"{n['noise_rms_dbfs']} dBFS → {n['false_starts_per_min']}/min" for n in v["noise_only"]) + ".", ""]

    # ---- LLM quality --------------------------------------------------------
    llms = load("llm_quality_*.json")
    if llms:
        from .llm_quality import rescore
        for d in llms:  # scoring rules are re-applied to the stored answers
            d["summary"].update(rescore(d["items"]))
        summary["llm_quality"] = [{"label": d["label"], "model": d["model"], "hardware": d["hardware_note"], **d["summary"]} for d in llms]
        L += ["## LLM probes with the agent's real context (keyword-scored)", "",
              "| Model | Context retention (en / he) | No hallucination on unknowns (en / he) | General facts (en / he) | Fact recalled after 10 / 20 filler turns | TTFT median (ms) | Hardware |",
              "|---|---:|---:|---:|---:|---:|---|"]
        for d in llms:
            s = d["summary"]
            lc = [i for i in d["items"] if i["kind"] == "long_context"]
            f = lambda k: f"{s[k]['en']['passed']}/{s[k]['en']['n']} · {s[k]['he']['passed']}/{s[k]['he']['n']}"  # noqa: E731
            L.append(f"| {d['label']} | {f('context_retention')} | {f('no_hallucination_on_unknowns')} | {f('general_facts')} | "
                     f"{' / '.join('pass' if i['pass'] else 'fail' for i in lc)} | {stat(s['ttft_ms'])} | {d['hardware_note']} |")
        L.append("")

    # ---- scenarios ----------------------------------------------------------
    scs = load("scenarios_*.json")
    if scs:
        summary["scenarios"] = [{"provider": d["provider"], "hardware": d["hardware_note"], "file": d["_file"], **d.get("aggregate", {})} for d in scs]
        L += ["## Scripted conversation scenarios (full pipeline through the WebSocket)", ""]
        for d in scs:
            a = d.get("aggregate", {})
            lat = a.get("response_latency_ms", {})
            it = a.get("interruptions", {})
            L += [f"### `{d['provider']}` — {d['hardware_note']}", "",
                  f"- Scenarios run: {a.get('scenarios')} (failed: {a.get('scenarios_failed')}); user turns: {a.get('turns')} (no response: {a.get('turns_without_response')})",
                  f"- Response latency (end of user speech → first agent audio): median {stat(lat)} ms, p95 {stat(lat, 'p95')} ms, n={lat.get('n', 0)}",
                  f"- Proactive opener, first audio after connect: median {stat(a.get('opener_first_audio_ms'))} ms",
                  f"- Stage medians (ms): " + ", ".join(f"{k} {stat(v)}" for k, v in sorted(a.get('stage_medians_ms', {}).items())),
                  f"- Scripted checks passed: {a.get('checks_passed')}/{a.get('checks_total')}" + (f" — failed: {', '.join(a['checks_failed'])}" if a.get("checks_failed") else ""),
                  f"- Interruptions: {it.get('detected')}/{it.get('attempted')} detected; speech onset → interrupt signalled median {stat(it.get('onset_to_interrupt_ms'))} ms; "
                  f"audio still arriving after the interrupt: median {stat(it.get('audio_after_interrupt_ms'))} ms",
                  f"- WER of the pipeline's transcripts on synthetic user speech: " + ", ".join(f"{k}: {pct(v['wer_clean'])} clean / {pct(v['wer_all'])} all (n={v['n']})" for k, v in a.get("wer_synthetic_speech", {}).items()),
                  f"- Playout underruns per agent turn: {a.get('playout_underruns_per_turn')}", "",
                  "| Scenario | Turns | Latency per turn (ms) | Checks | Error |", "|---|---:|---|---|---|"]
            for r in d["results"]:
                checks = " ".join(("✓" if c["pass"] else "✗") + c["check"] for c in r["checks"])
                L.append(f"| {r['id']} {r['title']} | {len(r['turns'])} | {', '.join(str(t.get('latency_ms', 'none')) for t in r['turns'])} | {checks} | {r.get('error') or ''} |")
            L.append("")

    # ---- concurrency --------------------------------------------------------
    cons = load("concurrency_*.json")
    if cons:
        summary["concurrency"] = [{k: v for k, v in d.items() if k != "_file"} for d in cons]
        L += ["## Concurrency ramp", ""]
        for d in cons:
            L += [f"### `{d['provider']}` — {d['hardware_note']}", "",
                  f"Targets: median ≤ {d['targets_ms']['median']} ms, p95 ≤ {d['targets_ms']['p95']} ms. Maximum sustainable concurrency: **{d.get('max_sustainable_concurrency')}**", "",
                  "| Concurrent sessions | Latency median (ms) | p95 (ms) | Failed turns | Failed sessions | Underruns | Server CPU mean / max | Late client frames |", "|---:|---:|---:|---:|---:|---:|---|---:|"]
            for lv in d["levels"]:
                r = lv.get("server_resources_last_60s") or {}
                cpu = f"{r.get('cpu_pct_mean', '–')}% / {r.get('cpu_pct_max', '–')}%" if r else "–"
                L.append(f"| {lv['concurrent_sessions']} | {stat(lv['response_latency_ms'])} | {stat(lv['response_latency_ms'], 'p95')} | {lv['turns_failed']}/{lv['turns_attempted']} | "
                         f"{lv['sessions_failed']} | {lv['underruns']} | {cpu} | {lv['client_late_mic_frames']} |")
            L.append("")

    # ---- long session -------------------------------------------------------
    longs = load("long_session_*.json")
    if longs:
        summary["long_session"] = [{k: v for k, v in d.items() if k not in ("turns", "_file")} for d in longs]
        L += ["## Extended session", "",
              "| Provider | Hardware | Minutes | Survived | Turns ok / failed | Latency median first third → last third (ms) | Underruns | Memory probe |", "|---|---|---:|---|---:|---|---:|---|"]
        for d in longs:
            mp = d.get("memory_probe", {})
            L.append(f"| `{d['provider']}` | {d['hardware_note']} | {d['actual_minutes']} | {d['session_survived']} | {d['turns_completed']} / {d['turns_failed']} | "
                     f"{stat(d['latency_first_third_ms'])} → {stat(d['latency_last_third_ms'])} | {d['underruns']} | {'pass' if mp.get('pass') else 'fail' if mp else 'not run'} |")
        L.append("")

    OUT.mkdir(exist_ok=True)
    (OUT / "benchmark_summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=1), encoding="utf-8")
    (OUT / "benchmark_summary.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
